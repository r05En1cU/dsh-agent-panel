#!/usr/bin/env node
/**
 * Install dsh-agent-panel (the PAT project-space plugin) into a DSH profile.
 *
 * The installer performs exactly two changes:
 *   1. copies the two built plugin packages into <profile>/node_modules/@deepseek-ai/;
 *   2. appends one marked block of loader rows to <profile>/cordis.patch.yml.
 *
 * It never starts, restarts, or kills a DSH host. Restart or reload the host yourself.
 * The live desktop profile is refused unless --allow-desktop is passed explicitly.
 *
 * Usage:
 *   node install-into-profile.mjs --profile "<profile directory>" [--dry-run] [--allow-desktop]
 */
import { copyFileSync, cpSync, existsSync, mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs'
import { homedir } from 'node:os'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath, pathToFileURL } from 'node:url'

const HERE = dirname(fileURLToPath(import.meta.url))
const MARK_START = '# >>> dsh-agent-panel install (managed)'
const MARK_END = '# <<< dsh-agent-panel install (managed)'
const PACKAGES = [
  { dir: 'dsh-experimental-collaboration-records', rowId: 'collaboration-records' },
  { dir: 'dsh-experimental-client-ui-project-space', rowId: 'ui-project-space' },
]

function parseArgs(argv) {
  const options = { profile: null, dryRun: false, allowDesktop: false }
  for (let index = 0; index < argv.length; index += 1) {
    const arg = argv[index]
    if (arg === '--profile') {
      options.profile = argv[index + 1]
      index += 1
    } else if (arg === '--dry-run') options.dryRun = true
    else if (arg === '--allow-desktop') options.allowDesktop = true
    else if (arg === '--help' || arg === '-h') options.help = true
    else throw new Error('unknown argument: ' + arg)
  }
  if (!options.help && !options.profile) throw new Error('--profile is required')
  return options
}

function isLiveDesktop(profile) {
  const live = resolve(homedir(), '.dsh', 'profiles', 'desktop')
  return resolve(profile).toLowerCase() === live.toLowerCase()
}

function stripManagedBlock(text) {
  const start = text.indexOf(MARK_START)
  if (start === -1) return text
  const end = text.indexOf(MARK_END, start)
  if (end === -1) throw new Error('managed block marker start found without its end marker')
  return text.slice(0, start) + text.slice(end + MARK_END.length).replace(/^\r?\n/, '')
}

function readManifest(dir) {
  const manifest = JSON.parse(readFileSync(join(dir, 'package.json'), 'utf8'))
  if (typeof manifest.name !== 'string') throw new Error('missing package name in ' + dir)
  return manifest
}

const options = parseArgs(process.argv.slice(2))
if (options.help) {
  console.log('usage: node install-into-profile.mjs --profile "<profile directory>" [--dry-run] [--allow-desktop]')
  process.exit(0)
}

const profile = resolve(options.profile)
if (!existsSync(profile)) throw new Error('profile directory does not exist: ' + profile)
if (isLiveDesktop(profile) && !options.allowDesktop) {
  throw new Error('refusing the live desktop profile without --allow-desktop')
}

const patchPath = join(profile, 'cordis.patch.yml')
const patchText = existsSync(patchPath) ? readFileSync(patchPath, 'utf8') : ''
const stripped = stripManagedBlock(patchText)
const rows = []

for (const entry of PACKAGES) {
  const source = join(HERE, 'packages', entry.dir)
  const manifest = readManifest(source)
  const destination = join(profile, 'node_modules', ...manifest.name.split('/'))
  rows.push(`- insert:
    - id: ${entry.rowId}
      name: '${pathToFileURL(join(destination, 'lib', 'index.js')).href}'`)
  if (options.dryRun) {
    console.log('[dry-run] copy ' + source + ' -> ' + destination)
    continue
  }
  if (existsSync(destination)) rmSync(destination, { recursive: true, force: true })
  mkdirSync(dirname(destination), { recursive: true })
  cpSync(source, destination, { recursive: true })
  console.log('installed ' + manifest.name + ' -> ' + destination)
}

const block = [MARK_START, '# Generated by install-into-profile.mjs. Remove with uninstall-from-profile.mjs.', ...rows, MARK_END].join('\n')
const nextPatch = (stripped.replace(/\s*$/, '') + '\n\n' + block + '\n').replace(/^\n+/, '')
if (options.dryRun) {
  console.log('[dry-run] would write ' + patchPath)
  console.log(block)
  process.exit(0)
}
if (existsSync(patchPath)) {
  const stamp = new Date().toISOString().replace(/[:.]/g, '-')
  copyFileSync(patchPath, patchPath + '.bak-' + stamp)
}
writeFileSync(patchPath, nextPatch, 'utf8')
console.log('updated ' + patchPath + ' (backup kept beside it)')
console.log('restart or reload the DSH host, then open a session: Workflow / Summary tabs and the Records header action appear.')
